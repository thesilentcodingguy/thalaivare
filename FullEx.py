# STEP 2: IMPORT LIBRARIES
import numpy as np
import matplotlib.pyplot as plt
import tensorflow as tf
import tensorflow_datasets as tfds

from tensorflow.keras.applications import VGG16
from tensorflow.keras.applications.vgg16 import preprocess_input


# ============================================================
# STEP 3: LOAD IMAGENETTE DATASET
# ============================================================

(train_ds, test_ds), info = tfds.load(
    "imagenette/320px-v2",
    split=["train", "validation"],
    as_supervised=True,
    with_info=True
)

class_names = [
    "tench",
    "English springer",
    "cassette player",
    "chain saw",
    "church",
    "French horn",
    "garbage truck",
    "gas pump",
    "golf ball",
    "parachute"
]

print("Dataset loaded!")
print("Number of classes:", len(class_names))


# ============================================================
# STEP 4: SELECT SOME IMAGES
# ============================================================

images = []
labels = []
count = [0] * 10

for image, label in train_ds:

    label = int(label.numpy())

    if count[label] < 5:
        images.append(image.numpy())
        labels.append(label)
        count[label] += 1

    if all(c == 5 for c in count):
        break

print("Images selected:", len(images))


# ============================================================
# STEP 5: LOAD PRETRAINED VGG16
# ============================================================

model = VGG16(
    weights="imagenet",
    include_top=True
)

print("VGG16 loaded!")
print("Input shape :", model.input_shape)
print("Output shape:", model.output_shape)


# ============================================================
# STEP 6: SELECT ONE IMAGE
# ============================================================

np.random.seed(42)

index = np.random.randint(len(images))

original_image = images[index]
original_label = class_names[labels[index]]
print("\nOriginal class:", original_label)
print("Original shape:", original_image.shape)

plt.figure(figsize=(5, 5))
plt.imshow(original_image)
plt.title("Input Image: " + original_label)
plt.axis("off")
plt.show()


# ============================================================
# STEP 7: RESIZE AND PREPROCESS IMAGE
# ============================================================

image = tf.image.resize(
    original_image,
    (224, 224)
).numpy()

image = image.astype(np.float32)

# Add batch dimension
image = np.expand_dims(image, axis=0)

# VGG16 preprocessing
processed_image = preprocess_input(image)

print("\nProcessed image shape:", processed_image.shape)


# ============================================================
# STEP 8: SELECT THREE VGG16 LAYERS
# ============================================================

layers = [
    "block1_conv2",   # Early layer
    "block3_conv3",   # Intermediate layer
    "block5_conv3"    # Deep layer
]

print("\nSelected layers:")

for name in layers:
    print(name, "->", model.get_layer(name).output.shape)


# ============================================================
# STEP 9: EXTRACT FEATURE MAPS
# ============================================================

feature_model = tf.keras.Model(
    inputs=model.input,
    outputs=[
        model.get_layer(name).output
        for name in layers
    ]
)

features = feature_model.predict(
    processed_image,
    verbose=0
)

early = features[0][0]
middle = features[1][0]
deep = features[2][0]

print("\nFeature map shapes:")
print("Early        :", early.shape)
print("Intermediate :", middle.shape)
print("Deep         :", deep.shape)


# ============================================================
# STEP 10: VISUALIZE FEATURE MAPS
# ============================================================

feature_data = [
    ("Early - block1_conv2", early),
    ("Intermediate - block3_conv3", middle),
    ("Deep - block5_conv3", deep)
]

for title, feature in feature_data:

    plt.figure(figsize=(10, 8))

    for i in range(8):
        plt.subplot(2, 4, i + 1)

        plt.imshow(
            feature[:, :, i],
            cmap="viridis"
        )

        plt.title("Map " + str(i + 1))
        plt.axis("off")

    plt.suptitle(title)
    plt.tight_layout()
    plt.show()


# ============================================================
# STEP 11: EXTRACT LEARNED FILTERS
# ============================================================

conv_layer = model.get_layer("block1_conv1")

weights, biases = conv_layer.get_weights()

print("\nFilter information:")
print("Filter shape:", weights.shape)
print("Bias shape  :", biases.shape)


# ============================================================
# STEP 12: NORMALIZE FILTERS
# ============================================================

filters = weights

filters = (
    filters - filters.min()
) / (
    filters.max() - filters.min()
)


# ============================================================
# STEP 13: VISUALIZE FIRST 32 FILTERS
# ============================================================

plt.figure(figsize=(12, 7))

for i in range(32):

    plt.subplot(4, 8, i + 1)

    plt.imshow(filters[:, :, :, i])

    plt.title("Filter " + str(i + 1))
    plt.axis("off")

plt.suptitle("VGG16 Learned Filters - block1_conv1")
plt.tight_layout()
plt.show()


# ============================================================
# STEP 14: SUMMARY
# ============================================================

print("\n======================================")
print("EXPERIMENT SUMMARY")
print("======================================")

print("Dataset       : Imagenette")
print("CNN           : VGG16")
print("Pretrained on : ImageNet")
print("Input size    : 224 × 224 × 3")

print("\nFeature Maps:")
print("block1_conv2 :", early.shape)
print("block3_conv3 :", middle.shape)
print("block5_conv3 :", deep.shape)

print("\nFilters:")
print("Layer         : block1_conv1")
print("Number        : 64")
print("Size          : 3 × 3 × 3")

print("""
Conclusion:
The feature maps of different VGG16 layers were visualized.

Early layers detect simple features such as edges, colors
and textures. Intermediate layers detect shapes and object
parts, while deeper layers learn more complex and semantic
features.

The learned convolutional filters from the first layer were
also visualized.
""")
